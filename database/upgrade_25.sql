CREATE TABLE IF NOT EXISTS payout_reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id BIGINT NOT NULL UNIQUE REFERENCES payout_plan_batches(id),
 farmer_id BIGINT NOT NULL REFERENCES users(id),
 amount_grosze BIGINT NOT NULL CHECK(amount_grosze>0),
 status TEXT NOT NULL CHECK(status='reserved_test'),
 created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS payout_reservation_items (
 order_id BIGINT PRIMARY KEY REFERENCES payment_simulations(order_id),
 reservation_id BIGINT NOT NULL REFERENCES payout_reservations(id),
 amount_grosze BIGINT NOT NULL CHECK(amount_grosze>=0)
);
