CREATE TABLE IF NOT EXISTS payout_plan_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_id BIGINT NOT NULL REFERENCES users(id),
 payout_date TEXT NOT NULL,
 created_at TEXT NOT NULL,
 UNIQUE(farmer_id,payout_date)
);
CREATE TABLE IF NOT EXISTS payout_plan_items (
 order_id BIGINT PRIMARY KEY REFERENCES payment_simulations(order_id),
 batch_id BIGINT NOT NULL REFERENCES payout_plan_batches(id),
 seller_grosze BIGINT NOT NULL CHECK(seller_grosze>=0),
 commission_grosze BIGINT NOT NULL CHECK(commission_grosze>=0)
);
CREATE INDEX IF NOT EXISTS payout_plan_items_batch_idx ON payout_plan_items(batch_id);
