-- WiejskaPaka PostgreSQL schema v1. Execute on EMPTY database.
BEGIN;
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role VARCHAR(12) NOT NULL CHECK(role IN ('klient','rolnik','dostawca','admin'))
);
CREATE TABLE sessions (
 token_hash CHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at TEXT NOT NULL
);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);
CREATE TABLE login_attempts (
 email VARCHAR(254) PRIMARY KEY,
 failures INTEGER NOT NULL DEFAULT 0 CHECK(failures>=0),
 locked_until TEXT
);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_id BIGINT NOT NULL REFERENCES users(id),
 name VARCHAR(120) NOT NULL,
 price_grosze BIGINT NOT NULL CHECK(price_grosze>=1),
 delivery_grosze BIGINT NOT NULL CHECK(delivery_grosze>=0),
 stock BIGINT NOT NULL CHECK(stock>=0)
);
CREATE INDEX products_farmer_idx ON products(farmer_id);
CREATE TABLE farmer_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id),
 farm_name VARCHAR(120) NOT NULL,
 city VARCHAR(120) NOT NULL,
 description VARCHAR(1500) NOT NULL DEFAULT ''
);
CREATE TABLE pickup_points (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_id BIGINT NOT NULL REFERENCES users(id),
 name VARCHAR(120) NOT NULL,
 city VARCHAR(120) NOT NULL,
 street VARCHAR(180) NOT NULL,
 opening_hours VARCHAR(180) NOT NULL,
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))
);
CREATE INDEX pickup_points_farmer_idx ON pickup_points(farmer_id);
CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 buyer_id BIGINT NOT NULL REFERENCES users(id),
 farmer_id BIGINT NOT NULL REFERENCES users(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 quantity BIGINT NOT NULL CHECK(quantity>0),
 subtotal_grosze BIGINT NOT NULL CHECK(subtotal_grosze>=0),
 delivery_grosze BIGINT NOT NULL CHECK(delivery_grosze>=0),
 total_grosze BIGINT NOT NULL CHECK(total_grosze=subtotal_grosze+delivery_grosze),
 fulfillment VARCHAR(12) NOT NULL CHECK(fulfillment IN ('odbior','dostawa')),
 status TEXT NOT NULL,
 pickup_code TEXT NOT NULL UNIQUE,
 pin_hash TEXT NOT NULL,
 pin_attempts INTEGER NOT NULL DEFAULT 0 CHECK(pin_attempts BETWEEN 0 AND 5),
 pin_used INTEGER NOT NULL DEFAULT 0 CHECK(pin_used IN (0,1)),
 created_at TEXT NOT NULL,
 confirmed_at TEXT
);
CREATE INDEX orders_buyer_idx ON orders(buyer_id);
CREATE INDEX orders_farmer_idx ON orders(farmer_id);
CREATE TABLE order_locations (
 order_id BIGINT PRIMARY KEY REFERENCES orders(id),
 pickup_point_id BIGINT REFERENCES pickup_points(id),
 delivery_city VARCHAR(120),
 delivery_street VARCHAR(180),
 delivery_postal_code VARCHAR(6),
 CONSTRAINT location_method_check CHECK (
 (pickup_point_id IS NOT NULL AND delivery_city IS NULL AND delivery_street IS NULL AND delivery_postal_code IS NULL)
 OR (pickup_point_id IS NULL AND delivery_city IS NOT NULL AND delivery_street IS NOT NULL AND delivery_postal_code IS NOT NULL)
 )
);
CREATE TABLE schema_migrations(version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
INSERT INTO schema_migrations(version) VALUES(1);
COMMIT;
