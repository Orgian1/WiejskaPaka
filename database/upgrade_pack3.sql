-- Wykonać ręcznie na PostgreSQL przed użyciem endpointów pakietu 3.
CREATE TABLE IF NOT EXISTS seller_compliance (
 farmer_id BIGINT PRIMARY KEY REFERENCES users(id),
 rules_version TEXT NOT NULL, acknowledged_at TEXT NOT NULL,
 review_status TEXT NOT NULL DEFAULT 'pending' CHECK(review_status IN ('pending','approved','needs_information','rejected')),
 reviewed_by BIGINT REFERENCES users(id), reviewed_at TEXT, review_reason TEXT
);
CREATE TABLE IF NOT EXISTS seller_compliance_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_id BIGINT NOT NULL REFERENCES users(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 event_type TEXT NOT NULL, created_at TEXT NOT NULL
);
